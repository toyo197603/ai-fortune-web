
"use strict";
const SHICHU_STEMS = ["甲","乙","丙","丁","戊","己","庚","辛","壬","癸"];
const SHICHU_BRANCHES = ["子","丑","寅","卯","辰","巳","午","未","申","酉","戌","亥"];
const SHICHU_60 = Array.from(
  {length:60},
  (_,i)=>SHICHU_STEMS[i%10]+SHICHU_BRANCHES[i%12]
);

const TENMEI_MIN_YEAR = 1920;
const TENMEI_MAX_YEAR = 2030;

function tenmeiMod(n, m) {
  return ((n % m) + m) % m;
}

function tenmeiParseBirthdate(value) {
  const s = String(value).replace(/\D/g, "");
  if (!/^\d{8}$/.test(s)) {
    throw new Error("生年月日は西暦8桁で入力してください");
  }

  const y = Number(s.slice(0, 4));
  const m = Number(s.slice(4, 6));
  const d = Number(s.slice(6, 8));

  const date = new Date(Date.UTC(y, m - 1, d));

  if (
    y < TENMEI_MIN_YEAR ||
    y > TENMEI_MAX_YEAR ||
    date.getUTCFullYear() !== y ||
    date.getUTCMonth() !== m - 1 ||
    date.getUTCDate() !== d
  ) {
    throw new Error("生年月日が対応範囲外、または存在しない日付です");
  }

  return { year: y, month: m, day: d };
}

function tenmeiCalculateDayPillar(birthdate) {
  const { year, month, day } = tenmeiParseBirthdate(birthdate);

  const target = Date.UTC(year, month - 1, day);
  const base = Date.UTC(2000, 0, 1);

  const days = Math.round(
    (target - base) / 86400000
  );

  const index = tenmeiMod(days + 54, 60);

  return {
    index: index,
    pillar: SHICHU_60[index],
    stem: SHICHU_STEMS[index % 10],
    branch: SHICHU_BRANCHES[index % 12]
  };
}

function tenmeiCalculateYearPillar(birthdate, birthtime) {
  const { year, month, day } = tenmeiParseBirthdate(birthdate);

  const term = tenmeiGetSetsuiri(year, 2);

  if (!term || !Number.isFinite(term.timestamp)) {
    return {
      status: "needsVerification",
      reason: "立春時刻が未確認です"
    };
  }

  const hour = birthtime
    ? Number(String(birthtime).slice(0, 2))
    : 12;

  const minute = birthtime
    ? Number(String(birthtime).slice(3, 5))
    : 0;

  const birth = Date.UTC(
    year, month - 1, day, hour - 9, minute
  );

  const diff = birth - term.timestamp;

  if (Math.abs(diff) <= term.uncertaintyMs) {
    return {
      status: "needsVerification",
      reason: "立春の境界時刻に近いため確認が必要です"
    };
  }

  const setsuiriYear = diff < 0 ? year - 1 : year;
  const index = tenmeiMod(setsuiriYear - 1984, 60);

  return {
    status: "ok",
    year: setsuiriYear,
    index,
    pillar: SHICHU_60[index]
  };
}

function tenmeiCalculateYearPillarSafe(birthdate, birthtime) {
  const { year, month, day } = tenmeiParseBirthdate(birthdate);

  if (birthtime !== undefined && birthtime !== null && birthtime !== "") {
    return tenmeiCalculateYearPillar(birthdate, birthtime);
  }

  const term = tenmeiGetSetsuiri(year, 2);

  if (!term || !Number.isFinite(term.timestamp)) {
    return {
      status: "needsVerification",
      reason: "立春時刻が未確認です"
    };
  }

  const start = Date.UTC(year, month - 1, day, -9, 0);
  const end = start + 86400000;

  const margin = term.uncertaintyMs;

  if (
    start - margin <= term.timestamp &&
    end + margin >= term.timestamp
  ) {
    return {
      status: "needsVerification",
      reason: "出生時刻が不明で立春の境界を確定できません"
    };
  }

  const setsuiriYear = end < term.timestamp ? year - 1 : year;
  const index = tenmeiMod(setsuiriYear - 1984, 60);

  return {
    status: "ok",
    year: setsuiriYear,
    index,
    pillar: SHICHU_60[index]
  };
}

function tenmeiGetSetsuiri(year, month) {
  if (
    !Number.isInteger(year) ||
    !Number.isInteger(month) ||
    year < 1920 ||
    year > 2030 ||
    month < 1 ||
    month > 12
  ) {
    return null;
  }

  const table = globalThis.TENMEI_SETSUIRI_TABLE;

  if (!table || !Array.isArray(table[String(year)])) {
    return null;
  }

  const timestamp = table[String(year)][month - 1];

  if (!Number.isFinite(timestamp)) {
    return null;
  }

  return {
    timestamp,
    uncertaintyMs: 86400000
  };
}

